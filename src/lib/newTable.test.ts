import { describe, expect, it } from "vitest";
import { createTableStatements, newColumn, problems, starterColumns } from "./newTable";

const cols = (engine: Parameters<typeof starterColumns>[0]) => [
  ...starterColumns(engine).slice(0, 1),
  newColumn({ name: "email", type: engine === "sqlserver" ? "nvarchar(255)" : "varchar(255)", nullable: false, unique: true }),
  newColumn({ name: "plan", type: "text", default: "'free'" }),
];

describe("new table SQL", () => {
  it("writes each engine's spelling", () => {
    expect(createTableStatements("postgres", "public", "users", cols("postgres"))).toEqual([
      'CREATE TABLE public.users (\n  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  email varchar(255) NOT NULL UNIQUE,\n  plan text DEFAULT \'free\',\n  PRIMARY KEY (id)\n)',
    ]);
    expect(createTableStatements("mysql", "shop", "users", cols("mysql"))[0]).toBe(
      "CREATE TABLE `shop`.`users` (\n  `id` bigint AUTO_INCREMENT NOT NULL,\n  `email` varchar(255) NOT NULL UNIQUE,\n  `plan` text DEFAULT 'free',\n  PRIMARY KEY (`id`)\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4",
    );
    expect(createTableStatements("sqlite", "main", "users", cols("sqlite"))[0]).toContain('id INTEGER PRIMARY KEY AUTOINCREMENT');
    expect(createTableStatements("sqlite", "main", "users", cols("sqlite"))[0]).not.toContain("PRIMARY KEY (");
    const duck = createTableStatements("duckdb", "main", "users", cols("duckdb"));
    expect(duck[0]).toBe('CREATE SEQUENCE main.users_id_seq');
    expect(duck[1]).toContain("DEFAULT nextval('main.users_id_seq')");
    expect(createTableStatements("sqlserver", "dbo", "users", cols("sqlserver"))[0]).toContain("[id] bigint IDENTITY(1,1) NOT NULL");
    const ch = createTableStatements("clickhouse", "default", "users", cols("clickhouse"))[0];
    expect(ch).toContain("`plan` Nullable(text)");
    expect(ch).toMatch(/ENGINE = MergeTree\nORDER BY \(`id`\)$/);
  });

  it("explains what's missing", () => {
    expect(problems("postgres", "", cols("postgres"))).toBe("Name the table");
    expect(problems("postgres", "t", [newColumn({ name: "a" })])).toBe("Give a a type");
    expect(problems("postgres", "t", [newColumn({ name: "a", type: "int" }), newColumn({ name: "A", type: "int" })])).toMatch(/Two columns/);
    expect(problems("mysql", "t", [newColumn({ name: "a", type: "text", autoIncrement: true, primaryKey: true })])).toMatch(/integer/);
    expect(problems("mysql", "t", [newColumn({ name: "a", type: "int", autoIncrement: true })])).toMatch(/primary key/);
    expect(problems("postgres", "t", cols("postgres"))).toBeNull();
  });

  it("adds indexes and foreign keys", () => {
    const [create, index] = createTableStatements(
      "postgres",
      "shop",
      "orders",
      [newColumn({ name: "id", type: "bigint", primaryKey: true, nullable: false }), newColumn({ name: "user_id", type: "bigint" }), newColumn({ name: "status", type: "text" })],
      [{ id: "i", columns: ["user_id", "status"], unique: false }],
      [{ id: "f", column: "user_id", refSchema: "shop", refTable: "users", refColumn: "id", onDelete: "CASCADE" }],
    );
    expect(create).toContain("CONSTRAINT fk_orders_user_id FOREIGN KEY (user_id) REFERENCES shop.users (id) ON DELETE CASCADE");
    expect(index).toBe("CREATE INDEX idx_orders_user_id_status ON shop.orders (user_id, status)");
  });
});
